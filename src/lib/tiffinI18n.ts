const LANG_KEY = 'sndmart-tiffin-lang';

/** Kannada when the phone is set to Kannada, otherwise English; the customer's own choice always wins. */
export function initialTiffinLang(): TiffinLang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'kn') return saved;
  } catch {
    /* storage can be blocked */
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('kn') ? 'kn' : 'en';
}

export function saveTiffinLang(lang: TiffinLang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage can be blocked */
  }
}

export function tt(lang: TiffinLang, key: string, ...args: (string | number | null | undefined)[]): string {
  let s = TIFFIN_TEXT[lang][key] ?? TIFFIN_TEXT.en[key] ?? key;
  args.forEach((a, i) => {
    s = s.split(`{${i}}`).join(a == null ? '' : String(a));
  });
  return s;
}
